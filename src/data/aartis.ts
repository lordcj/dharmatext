// Helper function to get aarti by slug
export function getAartiBySlug(slug: string): Aarti | undefined {
    return aartis.find(a => a.slug === slug);
}

// Helper function to get verses for an aarti
export function getAartiVerses(aartiId: string): AartiVerse[] {
    return allAartiVerses.filter(v => v.aartiId === aartiId);
}
